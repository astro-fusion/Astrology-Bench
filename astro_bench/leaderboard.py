"""Render ``LEADERBOARD.md`` from ``results/*.json`` (ADR-002 grouping).

Sections in order: baselines (oracle, then random/constant/mock), models, systems
(``system``, ``app_tools``, ``system_ui``), then ablations. Model and system rows are
ranked by overall answer accuracy; baseline and ``ablation: nochart`` rows never are.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

from .runner import load_result
from .schema import RunResult, Stat
from .solvers import BASELINES

BASELINE_ORDER = {name: i for i, name in enumerate(BASELINES)}
SECTIONS = [
    ("Baselines", ("oracle", "baseline")),
    ("Models", ("model",)),
    ("Systems", ("system", "app_tools", "system_ui")),
]
HEADER = (
    "| # | solver | kind | date | input mode | level | n | answer acc [95% CI] | "
    "citation score | fabricated-citation rate | parse-error rate | Brier |"
)
RULE = "|---|---|---|---|---|---|---|---|---|---|---|---|"


def _pct(x: float | None) -> str:
    return "-" if x is None else f"{100 * x:.1f}%"


def _num(x: float | None, signed: bool = False) -> str:
    if x is None:
        return "-"
    return f"{x:+.3f}" if signed else f"{x:.3f}"


def kind_label(result: RunResult) -> str:
    return f"ablation: {result.ablation}" if result.ablation else result.kind


def _row(rank: str, result: RunResult, level: str, s: Stat) -> str:
    acc = f"{100 * s.answer_acc:.1f}% [{100 * s.answer_ci[0]:.1f}, {100 * s.answer_ci[1]:.1f}]"
    solver = (f"[{result.solver}](runs/{result.run_id}/CARD.md)" if result.disclosure
              else result.solver)
    return (f"| {rank} | {solver} | {kind_label(result)} | {result.created_at[:10]} "
            f"| {result.input_mode} | {level} | {s.n} | {acc} | {_num(s.citation_mean, True)} "
            f"| {_pct(s.fabricated_rate)} | {_pct(s.parse_error_rate)} | {_num(s.brier)} |")


def _baseline_key(result: RunResult) -> tuple[int, str, str]:
    return (BASELINE_ORDER.get(result.solver.split(":")[-1], 99), result.input_mode,
            result.solver)


def _block(results: Sequence[RunResult], ranked: bool) -> list[str]:
    lines = [HEADER, RULE]
    for i, result in enumerate(results, 1):
        rank = str(i) if ranked else "-"
        lines.append(_row(rank, result, "all", result.summary.overall))
        for level, s in result.summary.by_level.items():
            lines.append(_row("", result, level, s))
    return lines


def render(results: Sequence[RunResult]) -> str:
    lines = [
        "# Astro-Bench leaderboard",
        "",
        "Generated by `astro-bench leaderboard` from `results/*.json`; do not edit by hand.",
        "Answer accuracy is the mean answer score with a Wilson 95% interval. Citation score "
        "is the mean over citation-graded items (-1 fabricated or unsupported, 0 none, +1 "
        "matches the canon). Brier is computed on stated confidence. Rows are grouped by "
        "solver kind (ADR-002): baselines first, then models, then systems; only models and "
        "systems are ranked. `ablation: nochart` rows are never ranked.",
    ]
    main = [r for r in results if not r.ablation]
    for title, kinds in SECTIONS:
        group = [r for r in main if r.kind in kinds]
        if not group:
            continue
        ranked = title != "Baselines"
        if ranked:
            group.sort(key=lambda r: (-r.summary.overall.answer_acc, r.solver, r.input_mode))
        else:
            group.sort(key=_baseline_key)
        lines += ["", f"## {title}", ""] + _block(group, ranked)
    ablations = sorted((r for r in results if r.ablation), key=_baseline_key)
    if ablations:
        lines += ["", "## Ablations (not ranked)", ""] + _block(ablations, False)
    lines += ["", "## Runs", ""]
    for result in [*main, *ablations]:
        desc = f"; {result.solver_description}" if result.solver_description else ""
        sample = (f", sample n={result.sample_n} seed={result.sample_seed}"
                  if result.sample_n is not None else "")
        lines.append(f"- `{result.run_id}`: {result.solver} ({kind_label(result)}{desc}), "
                     f"input {result.input_mode}, split {result.split}, {result.item_count} "
                     f"items{sample}, bench {result.bench_version}, engine "
                     f"{result.engine_commit}, items sha256 `{result.items_sha256[:12]}`")
    return "\n".join(lines) + "\n"


def load_results(results_dir: str | Path) -> list[RunResult]:
    return [load_result(p) for p in sorted(Path(results_dir).glob("*.json"))]


def write_leaderboard(results_dir: str | Path, out: str | Path) -> Path:
    path = Path(out)
    path.write_text(render(load_results(results_dir)), encoding="utf-8")
    return path
