"""Render ``LEADERBOARD.md`` from ``results/*.json`` (baselines first)."""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

from .runner import load_result
from .schema import RunResult, Stat
from .solvers import BASELINES

BASELINE_ORDER = {name: i for i, name in enumerate(BASELINES)}


def _is_baseline(result: RunResult) -> bool:
    return result.provider == "baseline" or result.solver.split(":")[-1] in BASELINES


def _order(result: RunResult) -> tuple[int, float, str]:
    if _is_baseline(result):
        inner = result.solver.split(":")[-1]
        rank = BASELINE_ORDER.get(inner, 99) + (10 if result.solver.startswith("nochart:") else 0)
        return (0, float(rank), result.solver)
    return (1, -result.summary.overall.answer_acc, result.solver)


def _pct(x: float | None) -> str:
    return "-" if x is None else f"{100 * x:.1f}%"


def _num(x: float | None, signed: bool = False) -> str:
    if x is None:
        return "-"
    return f"{x:+.3f}" if signed else f"{x:.3f}"


def _row(result: RunResult, level: str, s: Stat) -> str:
    acc = f"{100 * s.answer_acc:.1f}% [{100 * s.answer_ci[0]:.1f}, {100 * s.answer_ci[1]:.1f}]"
    return (f"| {result.solver} | {level} | {s.n} | {acc} | {_num(s.citation_mean, True)} "
            f"| {_pct(s.fabricated_rate)} | {_pct(s.parse_error_rate)} | {_num(s.brier)} |")


def render(results: Sequence[RunResult]) -> str:
    ordered = sorted(results, key=_order)
    lines = [
        "# Astro-Bench leaderboard",
        "",
        "Generated by `astro-bench leaderboard` from `results/*.json`; do not edit by hand.",
        "Answer accuracy is the mean answer score with a Wilson 95% interval. Citation score "
        "is the mean over citation-graded items (-1 fabricated or unsupported, 0 none, +1 "
        "matches the canon). Brier is computed on stated confidence. Baselines come first.",
        "",
        "| solver | level | n | answer acc [95% CI] | citation score | fabricated-citation "
        "rate | parse-error rate | Brier |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for result in ordered:
        lines.append(_row(result, "all", result.summary.overall))
        for level, s in result.summary.by_level.items():
            lines.append(_row(result, level, s))
    lines += ["", "Runs:", ""]
    for result in ordered:
        lines.append(f"- `{result.run_id}`: {result.solver}, split {result.split}, "
                     f"{result.item_count} items, bench {result.bench_version}, engine "
                     f"{result.engine_commit}, items sha256 `{result.items_sha256[:12]}`")
    return "\n".join(lines) + "\n"


def load_results(results_dir: str | Path) -> list[RunResult]:
    return [load_result(p) for p in sorted(Path(results_dir).glob("*.json"))]


def write_leaderboard(results_dir: str | Path, out: str | Path) -> Path:
    path = Path(out)
    path.write_text(render(load_results(results_dir)), encoding="utf-8")
    return path
